INDEX = IndexSource("https://index.alai.sh/")
CKSUM_A = "a" * 64
CKSUM_B = "b" * 64


def raw(
    collections: list[str] | None = None,
    *,
    requires_ansible: str | None = None,
    groups: dict[str, list[str]] | None = None,
    overrides: dict[str, str] | None = None,
    ignore: list[str] | None = None,
    sources: dict[str, dict[str, object]] | None = None,
) -> RawManifest:
    return RawManifest(
        "alai.toml",
        collections=collections or [],
        requires_ansible=requires_ansible,
        groups=groups or {},
        overrides=overrides or {},
        ignore_requires_ansible=ignore or [],
        sources=sources or {},
    )


def locked(name: str, version: str = "1.0.0", **fields: object) -> LockedCollection:
    values: dict[str, object] = {"source": INDEX, "cksum": CKSUM_A, "size": 10}
    values.update(fields)
    return LockedCollection(name, Version(version), **values)  # pyright: ignore[reportArgumentType]


def example() -> Lock:
    return Lock(
        raw(
            ["community.general>=9,<11", "ansible.windows"],
            requires_ansible=">=2.17",
            groups={"test": ["ansible.posix"]},
            overrides={"ansible.netcommon": ">=6"},
            ignore=["some.collection"],
            sources={"community.general": {"index": "alai"}},
        ),
        [
            locked(
                "community.general",
                "10.7.2",
                cksum=CKSUM_B,
                size=2913455,
                requires_ansible=">=2.16.0",
                dependencies=("community.library_inventory_filtering_v1",),
            ),
            locked("ansible.windows", "3.2.0", requires_ansible=">=2.16"),
            locked("ansible.posix", "2.0.0"),
            locked("community.library_inventory_filtering_v1", "1.1.5"),
        ],
    )


def reparse(text: str) -> Lock:
    return parse_lock(loads(text), "alai.lock")


def same(a: Lock | None, b: Lock) -> bool:
    """Equal as locks: the rendered text is canonical, and leaves out where a lock's manifest was read from."""
    return a is not None and render_lock(a) == render_lock(b)


class TestRender:
    def test_layout(self) -> None:
        assert (
            render_lock(example())
            == f"""\
# This file is generated by `alai lock`. Don't edit it by hand: any changes,
# comments included, are lost the next time alai writes it.
version = 1
revision = 1

[overrides]
"ansible.netcommon" = ">=6"
ignore_requires_ansible = ["some.collection"]

[sources]
"community.general" = {{ index = "alai" }}

[project]
requires_ansible = ">=2.17"
collections = ["community.general>=9,<11", "ansible.windows"]
groups.test.collections = ["ansible.posix"]

[[collection]]
name = "ansible.posix"
version = "2.0.0"
source = {{ index = "https://index.alai.sh/" }}
sha256 = "{CKSUM_A}"
size = 10
dependencies = []

[[collection]]
name = "ansible.windows"
version = "3.2.0"
source = {{ index = "https://index.alai.sh/" }}
sha256 = "{CKSUM_A}"
size = 10
requires_ansible = ">=2.16"
dependencies = []

[[collection]]
name = "community.general"
version = "10.7.2"
source = {{ index = "https://index.alai.sh/" }}
sha256 = "{CKSUM_B}"
size = 2913455
requires_ansible = ">=2.16.0"
dependencies = ["community.library_inventory_filtering_v1"]

[[collection]]
name = "community.library_inventory_filtering_v1"
version = "1.1.5"
source = {{ index = "https://index.alai.sh/" }}
sha256 = "{CKSUM_A}"
size = 10
dependencies = []
"""
        )

    def test_round_trip(self) -> None:
        text = render_lock(example())

        assert reparse(text).collections == example().collections
        assert render_lock(reparse(text)) == text

    def test_empty(self) -> None:
        text = render_lock(Lock(raw(), []))

        assert "[overrides]" not in text
        assert "[project]\ncollections = []\n" in text
        assert same(reparse(text), Lock(raw(), []))

    def test_overrides_without_ignore(self) -> None:
        text = render_lock(Lock(raw(overrides={"a.b": "*"}), []))

        assert '[overrides]\n"a.b" = "*"\n' in text
        assert "ignore_requires_ansible" not in text

    def test_long_array_one_item_per_line(self) -> None:
        names = [f"namespace.collection_{i}>=1.0.0" for i in range(4)]

        text = render_lock(Lock(raw(names), []))

        assert 'collections = [\n    "namespace.collection_0>=1.0.0",\n' in text
        assert '    "namespace.collection_3>=1.0.0",\n]\n' in text
        assert reparse(text).manifest.collections == names

    def test_strings_escaped(self) -> None:
        odd = 'a "quoted" \\ back\tslash\n\x7f é'

        lock = Lock(raw([odd]), [locked("ns.coll", source=IndexSource(f"https://x/{odd}"))])

        parsed = reparse(render_lock(lock))

        assert same(parsed, lock)
        assert parsed.manifest.collections == [odd]
        source = parsed.collections[0].source
        assert isinstance(source, IndexSource)
        assert source.url == f"https://x/{odd}"

    def test_bare_and_quoted_keys(self) -> None:
        text = render_lock(Lock(raw(groups={"lint-only": [], "my group": []}), []))

        assert "groups.lint-only.collections = []" in text
        assert 'groups."my group".collections = []' in text
        assert set(reparse(text).manifest.groups) == {"lint-only", "my group"}

    def test_dependencies_sorted(self) -> None:
        lock = Lock(raw(), [locked("a.b", dependencies=("z.z", "c.c")), locked("c.c"), locked("z.z")])

        assert 'dependencies = ["c.c", "z.z"]' in render_lock(lock)


class TestParse:
    def test_unknown_keys_ignored(self) -> None:
        text = render_lock(example()).replace("version = 1\n", "version = 1\nfuture = true\n", 1)
        text = text.replace("size = 10\n", 'size = 10\nmirror_of = "x"\n', 1)

        assert same(reparse(text), example())

    @pytest.mark.parametrize("revision", ["revision = 99\n", ""])
    def test_any_revision(self, revision: str) -> None:
        # A higher revision only adds what this alai can ignore, and a missing one is 0; alai writes its own.
        text = render_lock(example()).replace("revision = 1\n", revision, 1)

        assert same(reparse(text), example())
        assert "revision = 1\n" in render_lock(reparse(text))

    @pytest.mark.parametrize(
        ("change", "match"),
        [
            (("version = 1", "version = 2"), "needs a newer alai: it's lock format 2, this alai reads 1"),
            (("version = 1", "version = 0"), "'version' must be at least 1"),
            (("version = 1", "version = true"), "'version' must be an integer"),
            (("version = 1", 'version = "1"'), "'version' must be an integer"),
            (("revision = 1", "revision = -1"), "'revision' must be an integer of at least 0"),
            (("revision = 1", "revision = true"), "'revision' must be an integer of at least 0"),
            (('name = "ansible.posix"', 'name = "Ansible.Posix"'), r"collection\[0\]: invalid collection name"),
            (('version = "2.0.0"', 'version = "2.0"'), r"collection\[0\]: invalid version '2\.0'"),
            (('name = "ansible.posix"', 'name = ""'), "'name' is required and must be a non-empty string"),
            (
                ('source = { index = "https://index.alai.sh/" }\nsha256 = "' + "a" * 64, 'sha256 = "' + "a" * 64),
                r"'source' is required and must be a table",
            ),
            (
                ('source = { index = "https://index.alai.sh/" }', 'source = { svn = "https://g/x.git" }'),
                r"unknown source \(svn\); it may need a newer alai",
            ),
            (
                ('source = { index = "https://index.alai.sh/" }', 'source = { git = "https://g/x.git", tag = "v1" }'),
                r"unknown git source \(git, tag\); it may need a newer alai",
            ),
            (
                ('source = { index = "https://index.alai.sh/" }', 'source = { git = "https://g/x.git" }'),
                "'commit' is required and must be a non-empty string",
            ),
            (
                (
                    'source = { index = "https://index.alai.sh/" }',
                    'source = { git = "https://g/x.git", commit = "abc" }',
                ),
                "'commit' must be a full lowercase hex commit hash",
            ),
            (
                (
                    'source = { index = "https://index.alai.sh/" }',
                    'source = { git = "https://g/x.git", subdirectory = "../x", commit = "' + "a" * 40 + '" }',
                ),
                "'subdirectory' must be a relative path inside the repository",
            ),
            (
                ('source = { index = "https://index.alai.sh/" }', 'source = { index = "u", path = "p" }'),
                r"unknown source \(index, path\)",
            ),
            (('sha256 = "' + "a" * 64 + '"', 'sha256 = "ABC"'), "'sha256' must be a lowercase hex sha256"),
            (("size = 10", "size = -1"), "'size' is required and must be a non-negative integer"),
            (("size = 10", "size = true"), "'size' is required and must be a non-negative integer"),
            (('requires_ansible = ">=2.16"', "requires_ansible = 2"), "'requires_ansible' must be a string"),
            (("dependencies = []", "dependencies = [1]"), "'dependencies' must be an array of collection names"),
            (
                ('dependencies = ["community.library_inventory_filtering_v1"]', 'dependencies = ["x.y"]'),
                "'community.general' depends on 'x.y', which isn't locked",
            ),
        ],
    )
    def test_invalid(self, change: tuple[str, str], match: str) -> None:
        text = render_lock(example())
        assert change[0] in text, change[0]

        with pytest.raises(LockError, match=match):
            _ = reparse(text.replace(change[0], change[1], 1))

    @pytest.mark.parametrize(
        ("table", "match"),
        [
            ({"version": 1, "project": "x"}, "'project' must be a table"),
            ({"version": 1, "project": {"requires_ansible": 2}}, r"'project\.requires_ansible' must be a string"),
            ({"version": 1, "project": {"collections": "x"}}, r"'project\.collections' must be an array of strings"),
            ({"version": 1, "project": {"groups": []}}, r"'project\.groups' must be a table"),
            ({"version": 1, "project": {"groups": {"t": 1}}}, r"'project\.groups\.t' must be a table"),
            (
                {"version": 1, "project": {"groups": {"t": {"collections": [1]}}}},
                r"'project\.groups\.t\.collections' must be an array of strings",
            ),
            ({"version": 1, "overrides": []}, "'overrides' must be a table"),
            ({"version": 1, "overrides": {"a.b": 1}}, r'overrides\."a\.b" must be a string'),
            (
                {"version": 1, "overrides": {"ignore_requires_ansible": "a.b"}},
                r"'overrides\.ignore_requires_ansible' must be an array of strings",
            ),
            ({"version": 1, "sources": []}, "'sources' must be a table"),
            ({"version": 1, "sources": {"a.b": "x"}}, r'sources\."a\.b" must be a table of strings'),
            ({"version": 1, "collection": {}}, r"'collection' must be an array of tables"),
            ({"version": 1, "collection": [1]}, r"collection\[0\]: expected a table"),
        ],
    )
    def test_invalid_tables(self, table: dict[str, object], match: str) -> None:
        with pytest.raises(LockError, match=match):
            _ = parse_lock(table, "alai.lock")

    def test_duplicate(self) -> None:
        text = render_lock(Lock(raw(), [locked("a.b")]))
        entry = text[text.index("[[collection]]") :]

        with pytest.raises(LockError, match=r"collection\[1\]: 'a\.b' is locked more than once"):
            _ = reparse(text + "\n" + entry)

    def test_get(self) -> None:
        lock = example()

        assert lock.get("ansible.posix") == locked("ansible.posix", "2.0.0")
        assert lock.get("nope.nope") is None


class TestFile:
    def test_missing(self, tmp_path: Path) -> None:
        assert read_lock(lock_path(str(tmp_path))) is None

    def test_write_and_read(self, tmp_path: Path) -> None:
        path = lock_path(str(tmp_path))

        assert write_lock(path, example())
        assert same(read_lock(path), example())
        assert not write_lock(path, example())
        assert [p.name for p in tmp_path.iterdir()] == ["alai.lock"]

    def test_replaces_a_different_lock(self, tmp_path: Path) -> None:
        path = lock_path(str(tmp_path))
        _ = write_lock(path, Lock(raw(), []))

        assert write_lock(path, example())
        assert same(read_lock(path), example())

    def test_ordinary_permissions(self, tmp_path: Path) -> None:
        old = os.umask(0o022)
        try:
            _ = write_lock(lock_path(str(tmp_path)), example())
        finally:
            _ = os.umask(old)

        assert stat.S_IMODE((tmp_path / "alai.lock").stat().st_mode) == 0o644

    def test_invalid_toml(self, tmp_path: Path) -> None:
        _ = (tmp_path / "alai.lock").write_text("version = ")

        with pytest.raises(LockError, match=r"alai\.lock: invalid TOML"):
            _ = read_lock(lock_path(str(tmp_path)))

    def test_unwritable(self, tmp_path: Path) -> None:
        with pytest.raises(LockError, match="can't write"):
            _ = write_lock(str(tmp_path / "missing" / "alai.lock"), example())
        assert not (tmp_path / "missing").exists()


class TestIsCurrent:
    @staticmethod
    def manifest(toml: str) -> object:
        return parse_manifest(raw_manifest(loads(toml), "alai.toml"))

    BASE = """\
[project]
requires_ansible = ">=2.17"
collections = ["community.general>=9,<11", "ansible.windows"]
[project.groups.test]
collections = ["ansible.posix"]
[project.overrides]
"ansible.netcommon" = ">=6"
ignore_requires_ansible = ["some.collection"]
[project.sources]
"community.general" = { index = "alai" }
"""

    CURRENT = (
        BASE,
        BASE.replace(
            '"community.general>=9,<11", "ansible.windows"', '"ansible.windows", "community.general >= 9, < 11"'
        ),
        BASE.replace(">=6", ">=6.0.0"),
        BASE.replace(">=2.17", ">= 2.17.0"),
    )
    """Manifests that ask for what ``example()`` was locked from, only spelt or ordered differently."""

    @pytest.mark.parametrize("toml", CURRENT)
    def test_current(self, toml: str) -> None:
        assert example().is_current(self.manifest(toml))  # pyright: ignore[reportArgumentType]

    @pytest.mark.parametrize(
        "toml",
        [
            BASE.replace("<11", "<12"),
            BASE.replace(
                '"community.general" = { index = "alai" }',
                '"community.general" = { index = "alai" }\n"ansible.windows" = { index = "internal" }',
            ),
            BASE.replace('"community.general" = { index = "alai" }', '"community.general" = { index = "mirror" }'),
            BASE.replace(">=2.17", ">=2.18"),
            BASE.replace('["ansible.posix"]', '["ansible.posix", "community.crypto"]'),
            BASE.replace("[project.groups.test]", "[project.groups.lint]"),
            BASE.replace(">=6", ">=7"),
            BASE.replace('["some.collection"]', "[]"),
            BASE.replace('requires_ansible = ">=2.17"\n', ""),
        ],
    )
    def test_stale(self, toml: str) -> None:
        assert not example().is_current(self.manifest(toml))  # pyright: ignore[reportArgumentType]


class TestChanges:
    def test_each_kind(self) -> None:
        before = Lock(raw(), [locked("a.a", "1.0.0"), locked("b.b", "1.0.0"), locked("c.c", "1.0.0")])
        after = Lock(
            raw(),
            [locked("a.a", "2.0.0"), locked("b.b", "1.0.0", source=IndexSource("https://mirror/")), locked("d.d")],
        )

        assert changes(before, after) == [
            ("a.a", "Updated a.a v1.0.0 -> v2.0.0"),
            ("b.b", "Updated b.b v1.0.0, now from https://mirror/"),
            ("c.c", "Removed c.c v1.0.0"),
            ("d.d", "Added d.d v1.0.0"),
        ]

    def test_from_nothing(self) -> None:
        assert changes(None, Lock(raw(), [locked("a.a")])) == []

    def test_unchanged(self) -> None:
        assert changes(example(), example()) == []


class TestInputChanges:
    BASE = TestIsCurrent.BASE

    @pytest.mark.parametrize("toml", TestIsCurrent.CURRENT)
    def test_current(self, toml: str) -> None:
        # Spelling and order aren't changes, as is_current doesn't count them.
        assert input_changes(example(), TestIsCurrent.manifest(toml)) == []  # pyright: ignore[reportArgumentType]

    @pytest.mark.parametrize(
        ("toml", "expected"),
        [
            (
                BASE.replace("<11", "<12"),
                ["project.collections: changed community.general>=9,<11 to community.general>=9,<12"],
            ),
            (
                BASE.replace('"ansible.windows"]', '"ansible.windows", "c.c"]'),
                ["project.collections: added c.c"],
            ),
            (
                BASE.replace(', "ansible.windows"', ""),
                ["project.collections: removed ansible.windows"],
            ),
            (
                BASE.replace(
                    '"community.general" = { index = "alai" }',
                    '"community.general" = { index = "alai" }\n"ansible.windows" = { index = "internal" }',
                ),
                ["project.sources: added ansible.windows from 'internal'"],
            ),
            (
                BASE.replace('{ index = "alai" }', '{ index = "mirror" }'),
                ["project.sources: changed community.general from 'alai' to community.general from 'mirror'"],
            ),
            (BASE.replace(">=2.17", ">=2.18"), ["project.requires_ansible: changed >=2.17 to >=2.18"]),
            (BASE.replace('requires_ansible = ">=2.17"\n', ""), ["project.requires_ansible: removed >=2.17"]),
            (
                BASE.replace('["ansible.posix"]', '["ansible.posix", "community.crypto"]'),
                ["project.groups.test.collections: added community.crypto"],
            ),
            (
                BASE.replace("[project.groups.test]", "[project.groups.lint]"),
                ["project.groups.lint: added (ansible.posix)", "project.groups.test: removed (ansible.posix)"],
            ),
            (BASE.replace(">=6", ">=7"), ["project.overrides: changed ansible.netcommon>=6 to ansible.netcommon>=7"]),
            (
                BASE.replace('["some.collection"]', "[]"),
                ["project.overrides.ignore_requires_ansible: removed some.collection"],
            ),
        ],
    )
    def test_each_kind(self, toml: str, expected: list[str]) -> None:
        assert input_changes(example(), TestIsCurrent.manifest(toml)) == expected  # pyright: ignore[reportArgumentType]

    def test_empty_group_added(self) -> None:
        manifest = TestIsCurrent.manifest(self.BASE + "[project.groups.lint]\ncollections = []\n")

        assert input_changes(example(), manifest) == ["project.groups.lint: added (no collections)"]  # pyright: ignore[reportArgumentType]

    def test_requires_ansible_added(self) -> None:
        lock = Lock(raw(["a.a"]), [locked("a.a")])

        manifest = TestIsCurrent.manifest('[project]\nrequires_ansible = ">=2.18"\ncollections = ["a.a"]\n')

        assert input_changes(lock, manifest) == ["project.requires_ansible: added >=2.18"]  # pyright: ignore[reportArgumentType]


class TestSelect:
    LOCK = Lock(
        raw(["a.a"], groups={"dev": ["c.c"], "docs": ["d.d"]}),
        [
            locked("a.a", dependencies=("b.b",)),
            locked("b.b"),
            locked("c.c", dependencies=("b.b", "e.e")),
            locked("d.d"),
            locked("e.e"),
        ],
    )

    @staticmethod
    def names(collections: list[LockedCollection]) -> list[str]:
        return [c.name for c in collections]

    def test_project_with_dependencies(self) -> None:
        assert self.names(self.LOCK.select([])) == ["a.a", "b.b"]

    def test_groups(self) -> None:
        assert self.names(self.LOCK.select(["dev"])) == ["a.a", "b.b", "c.c", "e.e"]

    def test_groups_without_the_project(self) -> None:
        assert self.names(self.LOCK.select(["docs"], project=False)) == ["d.d"]

    def test_missing_entry(self) -> None:
        lock = Lock(raw(["a.a"]), [locked("a.a", dependencies=("gone.gone",))])

        with pytest.raises(LockError, match=r"no entry for gone\.gone"):
            _ = lock.select([])


class TestStale:
    MANIFEST = parse_manifest(raw(["a.a"]))

    def test_missing(self) -> None:
        assert stale(None, self.MANIFEST, [INDEX.url]) == "it doesn't exist"

    def test_current(self) -> None:
        assert stale(Lock(raw(["a.a"]), [locked("a.a")]), self.MANIFEST, [INDEX.url]) is None

    def test_manifest_changed(self) -> None:
        lock = Lock(raw(["a.a>=2"]), [locked("a.a")])

        assert stale(lock, self.MANIFEST, [INDEX.url]) == "alai.toml asks for something else than when it was locked"

    def test_index_gone(self) -> None:
        lock = Lock(raw(["a.a"]), [locked("a.a")])

        assert stale(lock, self.MANIFEST, ["https://other/"]) == (
            "a.a comes from https://index.alai.sh/, which isn't a configured index"
        )
