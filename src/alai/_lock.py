"""The lockfile, ``alai.lock``: what ``alai lock`` resolved, for ``alai sync`` to install.

The format and why it's shaped this way are in ``design/lockfile.md``. It's TOML, read with ``tomllib`` and written
by the small emitter here, which keeps the layout fixed so changes to a lock are small diffs.
"""

from __future__ import annotations

import collections.abc as _c
import os
import re
import secrets

from ._common import Error, Record, as_table
from ._config import RawManifest, read_toml
from ._manifest import Manifest, Requirement, collection_name, parse_manifest
from ._semver import Version

LOCK_FILE_NAME = "alai.lock"
LOCK_VERSION = 1
"""The lockfile format this alai reads and writes."""

_HEADER = (
    "# This file is generated by `alai lock`. Don't edit it by hand: any changes,\n"
    "# comments included, are lost the next time alai writes it.\n"
)
_SHA256_RE = re.compile(r"[0-9a-f]{64}")
_BARE_KEY_RE = re.compile(r"[A-Za-z0-9_-]+")
# An array longer than this goes one item per line, so adding an item changes one line of the diff.
_INLINE_ARRAY_WIDTH = 80


class LockError(Error):
    """A lockfile can't be read: it's malformed, or needs a newer alai."""


class IndexSource(Record):
    """A collection from an index, recorded by the index's root URL."""

    __slots__ = ("url",)

    def __init__(self, url: str) -> None:
        self.url = url


class LockedCollection(Record):
    __slots__ = ("cksum", "dependencies", "name", "requires_ansible", "size", "source", "version")

    def __init__(
        self,
        name: str,
        version: Version,
        *,
        source: IndexSource,
        cksum: str,
        size: int,
        requires_ansible: str | None = None,
        dependencies: tuple[str, ...] = (),
    ) -> None:
        self.name = name
        self.version = version
        self.source = source
        self.cksum = cksum
        """The artifact's sha256."""
        self.size = size
        self.requires_ansible = requires_ansible
        """The version's own ``requires_ansible``, as the index gave it, or None if it has none."""
        self.dependencies = dependencies
        """The names of the locked collections it depends on, sorted."""


class LockedRoot(Record):
    """The collection the project's root holds, locked as ``source = { editable = "." }``, as uv locks its own package:
    the checkout itself, linked in, so it has no checksum or size."""

    __slots__ = ("dependencies", "name", "path", "requires_ansible", "version")

    def __init__(
        self,
        name: str,
        version: Version,
        *,
        path: str = ".",
        requires_ansible: str | None = None,
        dependencies: tuple[str, ...] = (),
    ) -> None:
        self.name = name
        self.version = version
        self.path = path
        """Relative to the project root; always ``.`` until workspaces of several collections exist."""
        self.requires_ansible = requires_ansible
        self.dependencies = dependencies
        """The names of the locked collections its ``galaxy.yml`` asks for, sorted."""


class Lock(Record):
    __slots__ = ("collections", "manifest", "root")

    def __init__(
        self, manifest: RawManifest, collections: _c.Iterable[LockedCollection], root: LockedRoot | None = None
    ) -> None:
        self.root = root
        """A collection project's own collection; not in ``collections``. None in a playbook project."""
        self.manifest = manifest
        """What it was resolved from, as written in ``alai.toml``: the project's requirements and groups (the lock's
        ``[project]``), and the overrides and sources for the whole resolution (its ``[overrides]`` and
        ``[sources]``)."""
        self.collections = tuple(sorted(collections, key=lambda c: c.name))

    def get(self, name: str) -> LockedCollection | None:
        return next((c for c in self.collections if c.name == name), None)

    def select(self, groups: _c.Iterable[str], *, project: bool = True) -> list[LockedCollection]:
        """What installing the project's requirements, unless not ``project``, and those of ``groups`` needs: each
        collection they name and everything those depend on, sorted by name."""
        manifest = parse_manifest(self.manifest)
        wanted = [r.name for r in manifest.collections] if project else []
        for group in groups:
            wanted.extend(r.name for r in manifest.groups[group])
        by_name = {c.name: c for c in self.collections}
        found: set[str] = set()
        while wanted:
            name = wanted.pop()
            # The project's own collection is linked in, not installed from the lock's index entries.
            if name in found or (self.root is not None and name == self.root.name):
                continue
            collection = by_name.get(name)
            if collection is None:
                raise LockError(f"the lock has no entry for {name}, which it needs: run alai lock")
            found.add(name)
            wanted.extend(collection.dependencies)
        return [by_name[n] for n in sorted(found)]

    def is_current(self, manifest: Manifest) -> bool:
        """Whether this lock was resolved from a manifest that asks for the same as ``manifest``.

        Compared as parsed, so a change in whitespace or order in ``alai.toml`` doesn't make it stale.
        """
        return parse_manifest(self.manifest).resolution_key() == manifest.resolution_key()


def stale(lock: Lock | None, manifest: Manifest, index_urls: _c.Collection[str]) -> str | None:
    """Why ``lock`` is out of date for ``manifest`` and the configured index URLs, or None if it isn't.

    Checked without resolving or touching the network, so ``sync`` can tell quickly whether the lock needs
    resolving again: it's current when it exists, was resolved from a manifest asking for the same, and every
    collection's index is still configured. ``lock --check`` resolves instead, as ``uv lock --check`` does.
    """
    if lock is None:
        return "it doesn't exist"
    if not lock.is_current(manifest):
        return "alai.toml asks for something else than when it was locked"
    root = manifest.root
    if (lock.root is None) != (root is None) or (
        lock.root is not None
        and root is not None
        and (lock.root.name, lock.root.version, lock.root.requires_ansible)
        != (root.name, root.version, root.requires_ansible)
    ):
        return "galaxy.yml or meta/runtime.yml has changed since it was locked"
    for collection in lock.collections:
        if collection.source.url not in index_urls:
            return f"{collection.name} comes from {collection.source.url}, which isn't a configured index"
    return None


def changes(before: Lock | None, after: Lock) -> list[tuple[str, str]]:
    """What changed between two locks, one line per collection with its name, as uv reports it: added, updated or
    removed.

    Nothing when there was no lock before, as uv lists nothing for a new lock: every collection would be added.
    """
    if before is None:
        return []
    old = {c.name: c for c in before.collections}
    new = {c.name: c for c in after.collections}
    lines: list[tuple[str, str]] = []
    for name in sorted(old.keys() | new.keys()):
        was, now = old.get(name), new.get(name)
        if was is None and now is not None:
            lines.append((name, f"Added {name} v{now.version}"))
        elif now is None and was is not None:
            lines.append((name, f"Removed {name} v{was.version}"))
        elif was is not None and now is not None:
            if was.version != now.version:
                lines.append((name, f"Updated {name} v{was.version} -> v{now.version}"))
            elif was.source.url != now.source.url:
                lines.append((name, f"Updated {name} v{now.version}, now from {now.source.url}"))
    if before.root is not None and after.root is not None and before.root.version != after.root.version:
        name = after.root.name
        lines.append((name, f"Updated {name} v{before.root.version} -> v{after.root.version}"))
    return sorted(lines)


def input_changes(lock: Lock, manifest: Manifest) -> list[str]:
    """What ``manifest`` asks for that differs from the inputs ``lock`` was resolved from, one line per difference,
    named by its place in ``alai.toml``; nothing when ``lock.is_current(manifest)``. Compared as parsed, as
    ``is_current`` compares them, and shown as written."""
    before = parse_manifest(lock.manifest)
    lines: list[str] = []

    def compare(key: str, old: _c.Mapping[str, tuple[object, str]], new: _c.Mapping[str, tuple[object, str]]) -> None:
        # Each entry is (what's compared, how it's shown), by collection name.
        for name in sorted(old.keys() | new.keys()):
            was, now = old.get(name), new.get(name)
            if was is None and now is not None:
                lines.append(f"{key}: added {now[1]}")
            elif now is None and was is not None:
                lines.append(f"{key}: removed {was[1]}")
            elif was is not None and now is not None and was[0] != now[0]:
                lines.append(f"{key}: changed {was[1]} to {now[1]}")

    def requirements(items: _c.Iterable[Requirement]) -> dict[str, tuple[object, str]]:
        return {r.name: (r.req.clauses, str(r)) for r in items}

    compare("project.collections", requirements(before.collections), requirements(manifest.collections))

    def ansible(m: Manifest) -> dict[str, tuple[object, str]]:
        return {"": (m.requires_ansible, str(m.requires_ansible))} if m.requires_ansible is not None else {}

    compare("project.requires_ansible", ansible(before), ansible(manifest))
    for group in sorted(before.groups.keys() | manifest.groups.keys()):
        # A group added or removed whole is one line, with what it lists.
        if group not in manifest.groups or group not in before.groups:
            items = before.groups.get(group) or manifest.groups.get(group) or ()
            listed = ", ".join(sorted(str(r) for r in items)) or "no collections"
            verb = "removed" if group not in manifest.groups else "added"
            lines.append(f"project.groups.{group}: {verb} ({listed})")
            continue
        compare(
            f"project.groups.{group}.collections",
            requirements(before.groups[group]),
            requirements(manifest.groups[group]),
        )
    compare(
        "project.overrides",
        {n: (r.clauses, f"{n}{r}") for n, r in before.overrides.items()},
        {n: (r.clauses, f"{n}{r}") for n, r in manifest.overrides.items()},
    )
    compare(
        "project.overrides.ignore_requires_ansible",
        {n: (None, n) for n in before.ignore_requires_ansible},
        {n: (None, n) for n in manifest.ignore_requires_ansible},
    )
    compare(
        "project.sources",
        {n: (p.index, f"{n} from '{p.index}'") for n, p in before.sources.items()},
        {n: (p.index, f"{n} from '{p.index}'") for n, p in manifest.sources.items()},
    )
    return lines


def lock_path(project_root: str) -> str:
    return os.path.join(project_root, LOCK_FILE_NAME)


def read_lock(path: str) -> Lock | None:
    """The lock at ``path``, or None if there's no file there."""
    if not os.path.isfile(path):
        return None
    try:
        return parse_lock(read_toml(path), path)
    except Error as e:
        raise LockError(str(e)) from None


def parse_lock(table: _c.Mapping[str, object], path: str) -> Lock:
    version = table.get("version")
    if not isinstance(version, int) or isinstance(version, bool):
        raise LockError(f"{path}: 'version' must be an integer")
    if version > LOCK_VERSION:
        raise LockError(f"{path} needs a newer alai: it's lock format {version}, this alai reads {LOCK_VERSION}")
    if version < 1:
        raise LockError(f"{path}: 'version' must be at least 1")

    manifest = _parse_inputs(table, path)

    entries = table.get("collection", [])
    if not isinstance(entries, list):
        raise LockError(f"{path}: 'collection' must be an array of tables ([[collection]])")
    locked: dict[str, LockedCollection] = {}
    root: LockedRoot | None = None
    for i, entry in enumerate(_t_list(entries)):
        collection = _parse_collection(entry, f"{path}: collection[{i}]")
        if collection.name in locked or (root is not None and root.name == collection.name):
            raise LockError(f"{path}: collection[{i}]: '{collection.name}' is locked more than once")
        if isinstance(collection, LockedRoot):
            if root is not None:
                raise LockError(f"{path}: collection[{i}]: only one collection can be the project's own")
            root = collection
        else:
            locked[collection.name] = collection
    names = {*locked, *([root.name] if root is not None else [])}
    for collection in [*locked.values(), *([root] if root is not None else [])]:
        if missing := [d for d in collection.dependencies if d not in names]:
            raise LockError(f"{path}: '{collection.name}' depends on '{missing[0]}', which isn't locked")
    return Lock(manifest, locked.values(), root)


def render_lock(lock: Lock) -> str:
    """The lock as TOML, laid out the same way every time."""
    out = [_HEADER, f"version = {LOCK_VERSION}\n"]
    manifest = lock.manifest

    if manifest.overrides or manifest.ignore_requires_ansible:
        out.append("\n[overrides]\n")
        out.extend(f"{_key(name)} = {_string(req)}\n" for name, req in sorted(manifest.overrides.items()))
        if manifest.ignore_requires_ansible:
            out.append(f"ignore_requires_ansible = {_array(manifest.ignore_requires_ansible)}\n")

    if manifest.sources:
        out.append("\n[sources]\n")
        out.extend(f"{_key(name)} = {_inline(table)}\n" for name, table in sorted(manifest.sources.items()))

    out.append("\n[project]\n")
    if manifest.requires_ansible is not None:
        out.append(f"requires_ansible = {_string(manifest.requires_ansible)}\n")
    out.append(f"requirements = {_array(manifest.collections)}\n")
    out.extend(
        f"groups.{_key(name)}.requirements = {_array(manifest.groups[name])}\n" for name in sorted(manifest.groups)
    )

    root = lock.root
    for c in lock.collections:
        if root is not None and root.name < c.name:
            out.append(_render_root(root))
            root = None
        out.append("\n[[collection]]\n")
        out.append(f"name = {_string(c.name)}\n")
        out.append(f"version = {_string(c.version.text)}\n")
        out.append(f"source = {{ index = {_string(c.source.url)} }}\n")
        out.append(f"cksum = {_string(c.cksum)}\n")
        out.append(f"size = {c.size}\n")
        if c.requires_ansible is not None:
            out.append(f"requires_ansible = {_string(c.requires_ansible)}\n")
        out.append(f"dependencies = {_array(sorted(c.dependencies))}\n")
    if root is not None:
        out.append(_render_root(root))
    return "".join(out)


def _render_root(root: LockedRoot) -> str:
    out = ["\n[[collection]]\n", f"name = {_string(root.name)}\n", f"version = {_string(root.version.text)}\n"]
    out.append(f"source = {{ editable = {_string(root.path)} }}\n")
    if root.requires_ansible is not None:
        out.append(f"requires_ansible = {_string(root.requires_ansible)}\n")
    out.append(f"dependencies = {_array(sorted(root.dependencies))}\n")
    return "".join(out)


def write_lock(path: str, lock: Lock) -> bool:
    """Write the lock to ``path``, returning False if the file already held exactly this.

    Written beside it and renamed over it, so a lock is never left half written. It's a project file, so it gets
    ordinary permissions from the umask, not a temporary file's owner-only ones.
    """
    text = render_lock(lock)
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    temp = f"{path}.{secrets.token_hex(4)}.tmp"
    try:
        with open(temp, "x", encoding="utf-8", newline="\n") as f:
            _ = f.write(text)
        os.replace(temp, path)
    except OSError as e:
        if os.path.exists(temp):
            os.remove(temp)
        raise LockError(f"can't write {path}: {e.strerror or e}") from None
    return True


def _parse_inputs(table: _c.Mapping[str, object], path: str) -> RawManifest:
    """The lock's ``[project]`` and ``[overrides]``: what it was resolved from, as written in ``alai.toml``."""
    project = as_table(table.get("project", {}))
    if project is None:
        raise LockError(f"{path}: 'project' must be a table")
    requires_ansible = project.get("requires_ansible")
    if requires_ansible is not None and not isinstance(requires_ansible, str):
        raise LockError(f"{path}: 'project.requires_ansible' must be a string")
    requirements = _strings(project.get("requirements", []), f"{path}: 'project.requirements'")

    groups: dict[str, list[str]] = {}
    group_tables = as_table(project.get("groups", {}))
    if group_tables is None:
        raise LockError(f"{path}: 'project.groups' must be a table")
    for name, value in group_tables.items():
        group = as_table(value)
        if group is None:
            raise LockError(f"{path}: 'project.groups.{name}' must be a table")
        groups[name] = _strings(group.get("requirements", []), f"{path}: 'project.groups.{name}.requirements'")

    overrides: dict[str, str] = {}
    ignore: list[str] = []
    override_table = as_table(table.get("overrides", {}))
    if override_table is None:
        raise LockError(f"{path}: 'overrides' must be a table")
    for key, value in override_table.items():
        if key == "ignore_requires_ansible":
            ignore = _strings(value, f"{path}: 'overrides.ignore_requires_ansible'")
        elif isinstance(value, str):
            overrides[key] = value
        else:
            raise LockError(f'{path}: overrides."{key}" must be a string')

    sources: dict[str, dict[str, object]] = {}
    source_tables = as_table(table.get("sources", {}))
    if source_tables is None:
        raise LockError(f"{path}: 'sources' must be a table")
    for key, value in source_tables.items():
        source = as_table(value)
        if source is None or not all(isinstance(v, str) for v in source.values()):
            raise LockError(f'{path}: sources."{key}" must be a table of strings')
        sources[key] = source

    return RawManifest(
        path,
        collections=requirements,
        requires_ansible=requires_ansible,
        groups=groups,
        overrides=overrides,
        ignore_requires_ansible=ignore,
        sources=sources,
    )


def _strings(value: object, where: str) -> list[str]:
    if not isinstance(value, list) or not all(isinstance(v, str) for v in _t_list(value)):
        raise LockError(f"{where} must be an array of strings")
    return value  # pyright: ignore[reportUnknownVariableType]


def _parse_collection(entry: object, where: str) -> LockedCollection | LockedRoot:
    table = as_table(entry)
    if table is None:
        raise LockError(f"{where}: expected a table")

    name = _string_field(table, "name", where)
    try:
        _ = collection_name(name)
        version = Version(_string_field(table, "version", where))
    except ValueError as e:
        raise LockError(f"{where}: {e}") from None
    where = f"{where} ({name})"

    source_table = as_table(table.get("source"))
    if source_table is None:
        raise LockError(f"{where}: 'source' is required and must be a table, such as {{ index = \"...\" }}")
    requires_ansible = table.get("requires_ansible")
    if requires_ansible is not None and not isinstance(requires_ansible, str):
        raise LockError(f"{where}: 'requires_ansible' must be a string")
    dependencies = table.get("dependencies", [])
    if not isinstance(dependencies, list) or not all(isinstance(d, str) for d in _t_list(dependencies)):
        raise LockError(f"{where}: 'dependencies' must be an array of collection names")
    names = tuple(sorted(str(d) for d in _t_list(dependencies)))

    if set(source_table) == {"editable"}:
        if source_table["editable"] != ".":
            raise LockError(f"{where}: an editable source other than '.' needs a newer alai")
        return LockedRoot(name, version, requires_ansible=requires_ansible, dependencies=names)
    url = source_table.get("index")
    if not isinstance(url, str) or set(source_table) != {"index"}:
        kinds = ", ".join(sorted(source_table)) or "none"
        raise LockError(f"{where}: unknown source ({kinds}); it may need a newer alai")

    cksum = _string_field(table, "cksum", where)
    if not _SHA256_RE.fullmatch(cksum):
        raise LockError(f"{where}: 'cksum' must be a lowercase hex sha256")
    size = table.get("size")
    if not isinstance(size, int) or isinstance(size, bool) or size < 0:
        raise LockError(f"{where}: 'size' is required and must be a non-negative integer")

    return LockedCollection(
        name,
        version,
        source=IndexSource(url),
        cksum=cksum,
        size=size,
        requires_ansible=requires_ansible,
        dependencies=names,
    )


def _string_field(table: _c.Mapping[str, object], key: str, where: str) -> str:
    value = table.get(key)
    if not isinstance(value, str) or not value:
        raise LockError(f"{where}: '{key}' is required and must be a non-empty string")
    return value


def _t_list(value: list[object]) -> list[object]:
    # TOML arrays come back as list[Any]; this names them as list[object] for the type checker.
    return value


def _string(value: str) -> str:
    """A TOML basic string."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    escaped = re.sub(r"[\x00-\x1f\x7f]", lambda m: f"\\u{ord(m.group()):04x}", escaped)
    return f'"{escaped}"'


def _key(name: str) -> str:
    """A TOML key: bare when it can be, quoted otherwise, as a collection name with its dot must be."""
    return name if _BARE_KEY_RE.fullmatch(name) else _string(name)


def _inline(table: _c.Mapping[str, object]) -> str:
    """A TOML inline table of string values, keys sorted: ``{ index = "internal" }``."""
    return "{ " + ", ".join(f"{_key(k)} = {_string(str(v))}" for k, v in sorted(table.items())) + " }"


def _array(items: _c.Iterable[str]) -> str:
    strings = [_string(i) for i in items]
    inline = f"[{', '.join(strings)}]"
    if len(inline) <= _INLINE_ARRAY_WIDTH:
        return inline
    return "[\n" + "".join(f"    {s},\n" for s in strings) + "]"
